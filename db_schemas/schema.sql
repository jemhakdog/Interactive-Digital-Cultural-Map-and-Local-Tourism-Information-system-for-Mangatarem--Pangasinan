-- 4. BUSINESS PORTAL TABLES (Establishments, Rooms, Menu Items, Reviews)

CREATE TABLE IF NOT EXISTS ESTABLISHMENT (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    type VARCHAR(30) NOT NULL,
    description TEXT,
    address VARCHAR(500),
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    barangay_id INTEGER,
    contact_number VARCHAR(50),
    email VARCHAR(120),
    website VARCHAR(300),
    operating_hours JSONB,
    price_range VARCHAR(20),
    amenities JSONB,
    cover_image_url VARCHAR(500),
    logo_url VARCHAR(500),
    owner_id INTEGER NOT NULL,
    status VARCHAR(20) DEFAULT 'pending',
    is_featured BOOLEAN DEFAULT FALSE,
    rating_avg DOUBLE PRECISION DEFAULT 0,
    review_count INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (barangay_id) REFERENCES BARANGAY_INFO(id),
    FOREIGN KEY (owner_id) REFERENCES "USER"(id)
);

CREATE INDEX IF NOT EXISTS idx_establishment_type ON ESTABLISHMENT(type);
CREATE INDEX IF NOT EXISTS idx_establishment_status ON ESTABLISHMENT(status);
CREATE INDEX IF NOT EXISTS idx_establishment_owner ON ESTABLISHMENT(owner_id);
CREATE INDEX IF NOT EXISTS idx_establishment_coords ON ESTABLISHMENT(latitude, longitude);

CREATE TABLE IF NOT EXISTS ESTABLISHMENT_ROOM (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    price_per_night DECIMAL(10,2),
    capacity INTEGER DEFAULT 2,
    amenities JSONB,
    image_urls JSONB,
    is_available BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (establishment_id) REFERENCES ESTABLISHMENT(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ESTABLISHMENT_MENU_ITEM (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    establishment_id INTEGER NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    price DECIMAL(10,2),
    category VARCHAR(50),
    image_url VARCHAR(500),
    is_available BOOLEAN DEFAULT TRUE,
    is_bestseller BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (establishment_id) REFERENCES ESTABLISHMENT(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ESTABLISHMENT_REVIEW (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    establishment_id INTEGER NOT NULL,
    rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
    comment TEXT,
    status VARCHAR(20) DEFAULT 'pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES "USER"(id),
    FOREIGN KEY (establishment_id) REFERENCES ESTABLISHMENT(id) ON DELETE CASCADE
);
